package clearlydefined

import (
	"fmt"
	"sort"
	"strings"
	"time"

	"github.com/seebom-labs/bomhort/backend/internal/license"
)

// NoticePackage represents a component with its resolved license and optional
// attribution parties for inclusion in an attribution NOTICE file (#530).
type NoticePackage struct {
	Name             string
	Version          string
	PURL             string
	License          string
	CopyrightParties []string
}

// GenerateNotice creates a plain-text attribution NOTICE file containing every
// package with a resolved or unresolved license, real upstream copyright notices where available,
// explicit flags for packages requiring manual attribution review, and complete SPDX texts (#530, #62).
func GenerateNotice(targetName string, pkgs []NoticePackage) string {
	var b strings.Builder

	// Deduplicate by PURL when present, falling back to name + version + license when PURL is absent.
	// Distinct packages with the same name across different scopes (e.g. @team-a/core vs @team-b/core)
	// retain their distinct package identities (#530).
	dedup := make(map[string]*NoticePackage)
	var orderedKeys []string

	for _, p := range pkgs {
		lic := strings.TrimSpace(p.License)
		if lic == "" || lic == "NONE" {
			lic = "NOASSERTION"
		}
		purl := strings.TrimSpace(p.PURL)
		var k string
		if purl != "" {
			k = "purl:" + purl
		} else {
			k = fmt.Sprintf("pkg:%s|%s|%s", p.Name, p.Version, lic)
		}

		if existing, found := dedup[k]; found {
			existing.CopyrightParties = mergeStrings(existing.CopyrightParties, p.CopyrightParties)
		} else {
			cp := p
			cp.License = lic
			dedup[k] = &cp
			orderedKeys = append(orderedKeys, k)
		}
	}

	sort.Slice(orderedKeys, func(i, j int) bool {
		pi := dedup[orderedKeys[i]]
		pj := dedup[orderedKeys[j]]
		if pi.Name != pj.Name {
			return pi.Name < pj.Name
		}
		if pi.Version != pj.Version {
			return pi.Version < pj.Version
		}
		return pi.PURL < pj.PURL
	})

	totalComponents := len(orderedKeys)
	recordedAttributions := 0
	missingAttributions := 0
	unresolvedLicenses := 0
	referencedLicenses := make(map[string]bool)

	for _, k := range orderedKeys {
		p := dedup[k]
		if len(p.CopyrightParties) > 0 {
			recordedAttributions++
		} else {
			missingAttributions++
		}
		if p.License == "NOASSERTION" {
			unresolvedLicenses++
		} else if p.License != "" {
			ids := license.ExpressionIDs(p.License)
			if len(ids) == 0 {
				ids = []string{p.License}
			}
			for _, id := range ids {
				referencedLicenses[id] = true
			}
		}
	}

	b.WriteString("========================================================================\n")
	b.WriteString("Third-Party Software Notices and Information\n")
	if targetName != "" {
		b.WriteString(fmt.Sprintf("Target: %s\n", targetName))
	}
	b.WriteString(fmt.Sprintf("Generated by BOMHort on %s\n", time.Now().UTC().Format("2006-01-02 15:04:05 UTC")))
	b.WriteString("\nAttribution Coverage Summary:\n")
	b.WriteString(fmt.Sprintf("  Total third-party components: %d\n", totalComponents))
	b.WriteString(fmt.Sprintf("  Components with recorded copyright notices: %d\n", recordedAttributions))
	if missingAttributions > 0 {
		b.WriteString(fmt.Sprintf("  Components missing upstream copyright notice: %d (flagged for manual review)\n", missingAttributions))
	}
	if unresolvedLicenses > 0 {
		b.WriteString(fmt.Sprintf("  Components with unresolved licenses: %d (flagged for manual review)\n", unresolvedLicenses))
	}
	b.WriteString("========================================================================\n\n")

	b.WriteString("This product contains third-party software components subject to the\n")
	b.WriteString("following notices and license terms:\n\n")

	for _, k := range orderedKeys {
		p := dedup[k]
		b.WriteString("------------------------------------------------------------------------\n")
		b.WriteString(fmt.Sprintf("Package: %s\n", p.Name))
		if p.Version != "" {
			b.WriteString(fmt.Sprintf("Version: %s\n", p.Version))
		}
		if p.PURL != "" {
			b.WriteString(fmt.Sprintf("PURL: %s\n", p.PURL))
		}
		if p.License == "NOASSERTION" {
			b.WriteString("License: NOASSERTION [Unresolved license; manual review required]\n")
		} else {
			b.WriteString(fmt.Sprintf("License: %s\n", p.License))
		}

		b.WriteString("\nCopyright Notices:\n")
		if len(p.CopyrightParties) > 0 {
			for _, party := range p.CopyrightParties {
				b.WriteString(fmt.Sprintf("  %s\n", party))
			}
		} else {
			b.WriteString("  [No upstream copyright statement recorded; manual review required]\n")
		}

		b.WriteString("------------------------------------------------------------------------\n\n")
	}

	// Append complete SPDX license texts for all referenced licenses
	var sortedLicenses []string
	for lic := range referencedLicenses {
		sortedLicenses = append(sortedLicenses, lic)
	}
	sort.Strings(sortedLicenses)

	if len(sortedLicenses) > 0 {
		b.WriteString("========================================================================\n")
		b.WriteString("APPENDIX: FULL LICENSE TERMS\n")
		b.WriteString("========================================================================\n\n")

		for _, lic := range sortedLicenses {
			b.WriteString("########################################################################\n")
			b.WriteString(fmt.Sprintf("License Terms: %s\n", lic))
			b.WriteString("########################################################################\n\n")
			text := GetLicenseText(lic)
			b.WriteString(text)
			b.WriteString("\n\n")
		}
	}

	return b.String()
}

func mergeStrings(a, b []string) []string {
	seen := make(map[string]struct{}, len(a)+len(b))
	var out []string
	for _, s := range append(a, b...) {
		s = strings.TrimSpace(s)
		if s == "" {
			continue
		}
		if _, ok := seen[s]; !ok {
			seen[s] = struct{}{}
			out = append(out, s)
		}
	}
	return out
}
